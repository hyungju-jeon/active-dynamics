"""CISS RBF analysis script.

Loads rollouts generated by ``rbf_process.py`` and writes analysis figures.
"""

from __future__ import annotations

import argparse
import os

import matplotlib.pyplot as plt
import torch

import actdyn
from actdyn.utils import save_load
from actdyn.utils.runtime import ensure_dir
from actdyn.utils.visualize import (
    plot_observation_channels,
    plot_rollout_latent_comparison,
    plot_vector_field,
    set_matplotlib_style,
)


def _default_results_dir() -> str:
    return os.path.join(os.path.dirname(__file__), "../../results", "CISS", "RBF")


def run_analysis(base_dir: str | None = None) -> str:
    """Run post-processing visual analysis for RBF CISS outputs."""
    set_matplotlib_style()
    base_dir = ensure_dir(_default_results_dir() if base_dir is None else base_dir)

    rollouts_dir = os.path.join(base_dir, "rollouts")
    ro = save_load.load_and_concatenate_rollouts(rollouts_dir)

    z = ro["env_state"][0]
    z_hat = ro["model_state"][0]
    y = ro["obs"][0]

    fig, _ = plot_rollout_latent_comparison(
        z,
        z_hat,
        title="RBF: True vs Model Latent Trajectory",
    )
    fig.savefig(os.path.join(base_dir, "latent_trajectory_comparison.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)

    fig, _ = plot_observation_channels(
        y,
        n_channels=5,
        title="RBF: Observation Channels",
    )
    fig.savefig(os.path.join(base_dir, "observation_channels.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)

    metadata_path = os.path.join(base_dir, "run_metadata.pt")
    if os.path.exists(metadata_path):
        metadata = torch.load(metadata_path, map_location="cpu", weights_only=True)
        dyn_params = metadata.get("dyn_params")
        if dyn_params is not None:
            duffing_env = actdyn.VectorFieldEnv("duffing", x_range=5, dyn_params=dyn_params, dt=0.1, Q=0.0)
            fig = plt.figure(figsize=(6, 6))
            ax = fig.add_subplot(111)
            plot_vector_field(duffing_env.dynamics, ax=ax, x_range=4)
            ax.plot(z[:, 0].cpu(), z[:, 1].cpu(), alpha=0.7, label="true")
            ax.set_title("RBF: True Duffing Vector Field")
            ax.legend(loc="best")
            fig.savefig(os.path.join(base_dir, "true_vector_field.png"), dpi=150, bbox_inches="tight")
            plt.close(fig)

    return base_dir


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run CISS RBF analysis workflow")
    parser.add_argument("--base-dir", type=str, default=None)
    return parser


def main() -> None:
    args = _build_parser().parse_args()
    run_analysis(base_dir=args.base_dir)


if __name__ == "__main__":
    main()
